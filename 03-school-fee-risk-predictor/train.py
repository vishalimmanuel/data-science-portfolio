"""
Project 3: School Fee Late-Payment Risk Predictor
-------------------------------------------------
IMPORTANT: all data here is SYNTHETIC (generated by this script). No real student or
family information is used. The project demonstrates the full data-science workflow:
data generation -> cleaning -> exploration -> modelling -> evaluation -> a web app.

Run order:
  1. python train.py     (creates data, trains model, saves charts and model.joblib)
  2. streamlit run app.py
"""

from pathlib import Path

import joblib
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import seaborn as sns
from sklearn.compose import ColumnTransformer
from sklearn.ensemble import RandomForestClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import ConfusionMatrixDisplay, classification_report, roc_auc_score, RocCurveDisplay
from sklearn.model_selection import cross_val_score, train_test_split
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler

HERE = Path(__file__).parent
OUT = HERE / "outputs"
OUT.mkdir(exist_ok=True)
RANDOM_STATE = 42
sns.set_theme(style="whitegrid")

# 1. GENERATE SYNTHETIC DATA --------------------------------------------
rng = np.random.default_rng(RANDOM_STATE)
N = 1200

grade = rng.choice(["LKG-UKG", "1-5", "6-8", "9-11"], size=N, p=[0.15, 0.40, 0.30, 0.15])
base_fee = {"LKG-UKG": 900, "1-5": 1200, "6-8": 1500, "9-11": 1900}
monthly_fee = np.array([base_fee[g] for g in grade]) + rng.integers(-100, 101, size=N)

income_band = rng.choice(["Low", "Medium", "High"], size=N, p=[0.45, 0.40, 0.15])
siblings_in_school = rng.choice([0, 1, 2, 3], size=N, p=[0.45, 0.35, 0.15, 0.05])
distance_km = np.round(rng.gamma(2.0, 2.0, size=N), 1)
# lambda depends on income band (low income -> more late payments in the past)
lam = np.array([{"Low": 2.5, "Medium": 1.2, "High": 0.5}[i] for i in income_band])
late_payments_last_year = rng.poisson(lam)
parent_replies_to_messages = rng.choice(["Always", "Sometimes", "Rarely"], size=N, p=[0.5, 0.35, 0.15])
fee_concession = rng.choice([0, 1], size=N, p=[0.8, 0.2])

# Hidden rule that decides who pays late (the "truth" the model must discover).
score = (
    -2.0
    + 0.55 * late_payments_last_year
    + np.select([income_band == "Low", income_band == "Medium"], [1.0, 0.3], default=-0.8)
    + np.select([parent_replies_to_messages == "Rarely", parent_replies_to_messages == "Sometimes"], [1.0, 0.4], default=-0.3)
    + 0.0004 * (monthly_fee - 1300)
    + 0.08 * siblings_in_school
    + 0.03 * distance_km
    - 0.5 * fee_concession
    + rng.normal(0, 0.8, size=N)  # randomness so the problem isn't perfectly predictable
)
pays_late = (1 / (1 + np.exp(-score)) > 0.5).astype(int)

df = pd.DataFrame(
    {
        "grade_band": grade,
        "monthly_fee": monthly_fee,
        "income_band": income_band,
        "siblings_in_school": siblings_in_school,
        "distance_km": distance_km,
        "late_payments_last_year": late_payments_last_year,
        "parent_replies_to_messages": parent_replies_to_messages,
        "fee_concession": fee_concession,
        "pays_late": pays_late,
    }
)
df.to_csv(HERE / "synthetic_fee_data.csv", index=False)
print(f"Generated {len(df)} synthetic students. Late-payer share: {df['pays_late'].mean():.1%}")

# 2. EXPLORE ------------------------------------------------------------
fig, axes = plt.subplots(1, 3, figsize=(15, 4))
for ax, col in zip(axes, ["income_band", "parent_replies_to_messages", "grade_band"]):
    rate = df.groupby(col)["pays_late"].mean().sort_values()
    rate.plot.bar(ax=ax, color="#2a9d8f")
    ax.set_title(f"Late-payment rate by {col}")
    ax.set_ylabel("share paying late")
    ax.set_ylim(0, 1)
    ax.tick_params(axis="x", rotation=20)
plt.tight_layout()
plt.savefig(OUT / "late_rate_by_group.png", dpi=150)
plt.close()

plt.figure(figsize=(6, 4))
sns.boxplot(data=df, x="pays_late", y="late_payments_last_year")
plt.title("Past late payments vs paying late now")
plt.tight_layout()
plt.savefig(OUT / "past_late_boxplot.png", dpi=150)
plt.close()

# 3. MODEL --------------------------------------------------------------
X = df.drop(columns="pays_late")
y = df["pays_late"]
categorical = ["grade_band", "income_band", "parent_replies_to_messages"]
numeric = ["monthly_fee", "siblings_in_school", "distance_km", "late_payments_last_year", "fee_concession"]

prep = ColumnTransformer(
    [("cat", OneHotEncoder(handle_unknown="ignore"), categorical), ("num", StandardScaler(), numeric)]
)
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.2, random_state=RANDOM_STATE, stratify=y
)

candidates = {
    "Logistic Regression": Pipeline([("prep", prep), ("model", LogisticRegression(max_iter=1000))]),
    "Random Forest": Pipeline([("prep", prep), ("model", RandomForestClassifier(n_estimators=300, random_state=RANDOM_STATE))]),
}
print("\nCross-validation ROC-AUC (5 folds):")
cv = {}
for name, pipe in candidates.items():
    cv[name] = cross_val_score(pipe, X_train, y_train, cv=5, scoring="roc_auc").mean()
    print(f"  {name:<20} {cv[name]:.3f}")

best_name = max(cv, key=cv.get)
model = candidates[best_name].fit(X_train, y_train)
print(f"\nBest model: {best_name}")

# 4. EVALUATE -----------------------------------------------------------
pred = model.predict(X_test)
proba = model.predict_proba(X_test)[:, 1]
auc = roc_auc_score(y_test, proba)
report = classification_report(y_test, pred, target_names=["pays on time", "pays late"])
print(f"\nTest ROC-AUC: {auc:.3f}\n{report}")

(OUT / "results.txt").write_text(
    "NOTE: synthetic data.\n\nCross-validation ROC-AUC:\n"
    + "\n".join(f"  {n}: {s:.3f}" for n, s in cv.items())
    + f"\n\nBest model: {best_name}\nTest ROC-AUC: {auc:.3f}\n\n{report}"
)

ConfusionMatrixDisplay.from_predictions(y_test, pred, display_labels=["on time", "late"], cmap="Blues")
plt.title("Confusion matrix (test set)")
plt.tight_layout()
plt.savefig(OUT / "confusion_matrix.png", dpi=150)
plt.close()

RocCurveDisplay.from_predictions(y_test, proba)
plt.title("ROC curve (test set)")
plt.tight_layout()
plt.savefig(OUT / "roc_curve.png", dpi=150)
plt.close()

# Which factors push risk up? (works for both model types)
names = model.named_steps["prep"].get_feature_names_out()
inner = model.named_steps["model"]
values = inner.coef_[0] if hasattr(inner, "coef_") else inner.feature_importances_
imp = pd.Series(values, index=[n.split("__")[1] for n in names]).sort_values()
plt.figure(figsize=(7, 6))
imp.plot.barh(color="#e76f51")
plt.title("What drives late-payment risk" + (" (coefficients)" if hasattr(inner, "coef_") else " (importance)"))
plt.tight_layout()
plt.savefig(OUT / "risk_drivers.png", dpi=150)
plt.close()

# 5. SAVE MODEL FOR THE APP --------------------------------------------
joblib.dump(model, HERE / "model.joblib")
print(f"\nSaved model.joblib and charts in {OUT}")
